    [TestCase(2, -1000, 600, 28.096, typeof(ResponseSuccess)),
        TestCase(2, -1000, 600, 28.096, typeof(ResponseSuccess)),
        TestCase(2, 50, 600, 9.096, typeof(ResponseSuccess)),
        TestCase(1, 2450, 800, 58.11, typeof(ResponseSuccess)),
        TestCase(2, 850, 800, 26.11, typeof(ResponseSuccess)),
        TestCase(2, 850, 200, 23.07, typeof(ResponseSuccess)),
        TestCase(2, 50, 600, 9.096, typeof(ResponseSuccess)),
        TestCase(2, 2050, 1200, 52.132, typeof(ResponseSuccess)),
        TestCase(2, 850, 600, 25.096, typeof(ResponseSuccess)),
        TestCase(1, 850, 0, 0, typeof(ResponseSuccess)), // torque loss is 0 if speed is 0
        ]
    public void Gearbox_Request_engaged(int gear, double t, double n, double exploss, Type responseType)
    {
		var gearboxData = CreateGearboxData();
        var runData = new VectoRunData() {
			GearboxData = gearboxData,
			EngineData = new CombustionEngineData()
		};

		var container = GetMockVehicleContainer(runData);

		var shiftStrategy = new Mock<IShiftStrategy>();
		shiftStrategy
			.Setup(s => s.InitGear(It.IsAny<Second>(), It.IsAny<Second>(), It.IsAny<NewtonMeter>(),
				It.IsAny<PerSecond>())).Returns(new GearshiftPosition((uint)gear));

		var gearbox = new AMTGearbox(container.Object, shiftStrategy.Object);

        Second reqAbsTime = null;
		Second reqDt = null;
		NewtonMeter reqTorque = null;
		PerSecond reqAngularVelocity = null;
        var port = new Mock<ITnOutPort>();
		port.Setup(p =>
			p.Request(It.IsAny<Second>(), It.IsAny<Second>(), It.IsAny<NewtonMeter>(), It.IsAny<PerSecond>(), It.IsAny<bool>())).Returns(
			(Second absTime, Second dt, NewtonMeter outTorque, PerSecond outAngularVelocity, bool dryRun) => {
				reqAbsTime = absTime;
				reqDt = dt;
				reqTorque = outTorque;
				reqAngularVelocity = outAngularVelocity;
				return new ResponseSuccess(this) {
					AbsTime = absTime,
					SimulationInterval = dt,
				};
			});

        gearbox.InPort().Connect(port.Object);
       
        var ratios = new[] { 0.0, 6.38, 4.63, 3.44, 2.59, 1.86, 1.35, 1, 0.76 };
        // the first element 0.0 is just a placeholder for axlegear, not used in this test

        var absTime = 0.SI<Second>();
        var dt = 2.SI<Second>();

        var torque = t.SI<NewtonMeter>();
        var expectedN = n.RPMtoRad();
        var expectedLoss = exploss.SI<NewtonMeter>();

        var outTorque = (torque - expectedLoss) * ratios[gear];
        var angularVelocity = expectedN / ratios[gear];

        gearbox.OutPort().Initialize(outTorque, angularVelocity);

        Assert.AreEqual(gear, gearbox.Gear.Gear);

        gearbox.Gear = new GearshiftPosition((uint)gear);
        //container.AbsTime = absTime;
        var response = gearbox.OutPort().Request(absTime, dt, outTorque, angularVelocity, false);
        Assert.IsTrue(response.GetType() == responseType);

        AssertHelper.AreRelativeEqual(absTime, reqAbsTime);
        AssertHelper.AreRelativeEqual(dt, reqDt);
        AssertHelper.AreRelativeEqual(expectedN, reqAngularVelocity);
        AssertHelper.AreRelativeEqual(t, reqTorque, toleranceFactor: 1e-5);
    }

	private static Mock<IVehicleContainer> GetMockVehicleContainer(VectoRunData runData)
	{
		var container = new Mock<IVehicleContainer>();
		container.Setup(c => c.RunData).Returns(runData);
		var pi = new Mock<IPowertainInfo>();
		pi.Setup(p => p.HasCombustionEngine).Returns(true);
		container.Setup(c => c.PowertrainInfo).Returns(pi.Object);

		var veh = new Mock<IVehicleInfo>();
		veh.Setup(v => v.VehicleSpeed).Returns(0.KMPHtoMeterPerSecond());
		container.Setup(c => c.VehicleInfo).Returns(veh.Object);
		var driver = new Mock<IDriverInfo>();
		driver.Setup(d => d.DriverBehavior).Returns(DrivingBehavior.Driving);
		driver.Setup(d => d.DrivingAction).Returns(DrivingAction.Accelerate);
		container.Setup(c => c.DriverInfo).Returns(driver.Object);
		return container;
	}

