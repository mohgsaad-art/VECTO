	[TestCase(1),
	TestCase(2),
	]
	public void ElectricMotorModelDataTest(int count)
	{
		var electricMachine = GetElectricMachineDataV1(count);

		var dao = new EngineeringDataAdapter();


		var data = dao.CreateElectricMachines(electricMachine, null, null);
		var emModelData = data.First().Item2;

		Assert.AreEqual(0.15 * count, emModelData.Inertia.Value(), 1e-3);

		//Assert.AreEqual(2000, emModelData.ContinuousTorqueSpeed.AsRPM, 1e-3);
		Assert.AreEqual(238.7323 * count, emModelData.Overload.ContinuousTorque.Value(), 1e-3);

		Assert.AreEqual(334.23 * count, -emModelData.EfficiencyData.VoltageLevels.First().FullLoadCurve.FullLoadDriveTorque(2000.RPMtoRad()).Value(), 1e-3);
		Assert.AreEqual(-334.23 * count, -emModelData.EfficiencyData.VoltageLevels.First().FullLoadCurve.FullGenerationTorque(2000.RPMtoRad()).Value(), 1e-3);

		Assert.AreEqual(30 * count, emModelData.DragCurveLookup(2500.RPMtoRad(), 0u).Value(), 1e-3);

		Assert.AreEqual(-14579 * count,
			emModelData.EfficiencyData.VoltageLevels.First()
				.LookupElectricPower(190.99.RPMtoRad(), (-500 * count).SI<NewtonMeter>(), 0, false).ElectricalPower.Value(),
			1e-3);
	}

	[TestCase(225, 3724.21, 375, 4551.82, 120, 32133.6285)]
	[TestCase(220, 6207.03, 375, 4551.82, 120, 340.97849)]
	public void TestElectricMotorOverloadBufferTest(double contTq, double contSpdRpm, double ovlTq, double ovlSpdRpm, double ovlDuration, double expectedOvlBfr)
	{
		var componentData = GetEMInputDataDecl(contTq.SI<NewtonMeter>(), contSpdRpm.RPMtoRad(), ovlTq.SI<NewtonMeter>(), ovlSpdRpm.RPMtoRad(), ovlDuration.SI<Second>());


		var em = new XMLElectricMachinesDeclarationData(
			new List<ElectricMachineEntry<IElectricMotorDeclarationInputData>> {
				new ElectricMachineEntry<IElectricMotorDeclarationInputData>() {
					Count = 1,
					ElectricMachine = componentData
				}
			});
		var da = new ElectricMachinesDataAdapter();

		var modelData = da.CreateElectricMachines(em, null, 500.SI<Volt>());
		var emData = modelData.First().Item2;

		Assert.AreEqual(expectedOvlBfr, emData.Overload.OverloadBuffer.Value(), 0.1);
	}

    [TestCase()]
    public void TestElectricMotorV3_Lookup()
	{
		var inputProvider = GetElectricMachineDataV3(1);
			var daa = new ElectricMachinesDataAdapter();
        var emData = daa.CreateElectricMachines(inputProvider, null, null).First().Item2;


        Assert.AreEqual(26, emData.DragCurveLookup(2000.RPMtoRad(), 0u).Value());

        var em = emData.EfficiencyData;
        var gear = new GearshiftPosition(0);

        Assert.AreEqual(-334.2300, em.FullLoadDriveTorque(400.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());
        Assert.AreEqual(-396.076, em.FullLoadDriveTorque(600.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());
        Assert.AreEqual(-365.153, em.FullLoadDriveTorque(500.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());
        Assert.AreEqual(-380.6145, em.FullLoadDriveTorque(550.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());

        Assert.AreEqual(334.2300, em.FullGenerationTorque(400.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());
        Assert.AreEqual(406.076, em.FullGenerationTorque(600.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());
        Assert.AreEqual(370.153, em.FullGenerationTorque(500.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());
        Assert.AreEqual(388.1145, em.FullGenerationTorque(550.SI<Volt>(), 2000.RPMtoRad(), gear.Gear).Value());

        Assert.AreEqual(-101.70072, em.EfficiencyMapLookupTorque(400.SI<Volt>(), -25000.SI<Watt>(), 2000.RPMtoRad(), -300.SI<NewtonMeter>(), gear).Value(), 1e-3);
        Assert.AreEqual(-25000, em.LookupElectricPower(400.SI<Volt>(), 2000.RPMtoRad(), -101.70072.SI<NewtonMeter>(), gear).ElectricalPower.Value(), 1e-1);

        Assert.AreEqual(-114.51788, em.EfficiencyMapLookupTorque(600.SI<Volt>(), -25000.SI<Watt>(), 2000.RPMtoRad(), -300.SI<NewtonMeter>(), gear).Value(), 1e-3);
        Assert.AreEqual(-25000, em.LookupElectricPower(600.SI<Volt>(), 2000.RPMtoRad(), -114.51788.SI<NewtonMeter>(), gear).ElectricalPower.Value(), 1e-1);

        Assert.AreEqual(-107.772009, em.EfficiencyMapLookupTorque(500.SI<Volt>(), -25000.SI<Watt>(), 2000.RPMtoRad(), -300.SI<NewtonMeter>(), gear).Value(), 1e-3);
        Assert.AreEqual(-25000, em.LookupElectricPower(500.SI<Volt>(), 2000.RPMtoRad(), -107.772009.SI<NewtonMeter>(), gear).ElectricalPower.Value(), 1e-1);

        Assert.AreEqual(-111.053784, em.EfficiencyMapLookupTorque(550.SI<Volt>(), -25000.SI<Watt>(), 2000.RPMtoRad(), -300.SI<NewtonMeter>(), gear).Value(), 1e-3);
        Assert.AreEqual(-25000, em.LookupElectricPower(550.SI<Volt>(), 2000.RPMtoRad(), -111.053784.SI<NewtonMeter>(), gear).ElectricalPower.Value(), 1e-1);

    }

    private static IElectricMotorDeclarationInputData GetEMInputDataDecl(NewtonMeter contTq, PerSecond contSpd,
		NewtonMeter ovlTq, PerSecond ovlSpd, Second ovlDuration)
	{
		var inputData = new Mock<IElectricMotorDeclarationInputData>();
		inputData.Setup(i => i.Inertia).Returns(0.15.SI<KilogramSquareMeter>());

		var v1 = GetVoltageLevelDeclMock(contTq, contSpd, ovlTq, ovlSpd, ovlDuration);
		var v2 = GetVoltageLevelDeclMock(contTq, contSpd, ovlTq, ovlSpd, ovlDuration);
		v1.SetupGet(v => v.VoltageLevel).Returns(400.SI<Volt>());
		v2.SetupGet(v => v.VoltageLevel).Returns(600.SI<Volt>());

		inputData.SetupGet(i => i.VoltageLevels).Returns(new[] { v1.Object, v2.Object });
		inputData.SetupGet(i => i.DragCurve).Returns(InputDataHelper.InputDataAsTableData(EMDragHdr, EMDragData));
		inputData.SetupGet(i => i.CertificationMethod).Returns(CertificationMethod.Measured);

		return inputData.Object;
	}

